"""Merge per-module fragments into the shared project files.

pyproject.toml, requirements.txt, package.json, docker-compose.yml and .env.example
each collect contributions from every chosen module. Output is sorted and stable:
the same module set always produces the same bytes.
"""

from __future__ import annotations

import json
import re
from typing import Any

import tomli_w
import yaml

from .registry import Module

_NAME = re.compile(r"^([A-Za-z0-9_.\-]+)(\[[^\]]+\])?$")


def _pin(dep: str, versions: dict[str, str]) -> str:
    m = _NAME.match(dep.strip())
    if not m:
        return dep  # already has a specifier
    name, extras = m.group(1), m.group(2) or ""
    v = versions.get(name.lower())
    if not v:
        raise KeyError(f"no pinned version for python package '{name}' in modules/versions.yaml")
    return f"{name}{extras}=={v}"


def python_deps(mods: list[Module], versions: dict[str, str], extra: list[str] | None = None) -> tuple[list[str], list[str]]:
    deps: dict[str, str] = {}
    dev: dict[str, str] = {}
    for m in mods:
        for d in m.python_deps:
            deps[d.lower()] = _pin(d, versions)
        for d in m.dev_deps:
            dev[d.lower()] = _pin(d, versions)
    for d in extra or []:
        # Deps declared on custom tools may be unpinned; keep the user's specifier.
        key = re.split(r"[<>=!~\[ ]", d, maxsplit=1)[0].lower()
        if key and key not in deps:
            deps[key] = d if re.search(r"[<>=!~]", d) else (_pin(d, versions) if key in versions else d)
    return sorted(deps.values(), key=str.lower), sorted(dev.values(), key=str.lower)


def pyproject(name: str, description: str, deps: list[str], dev: list[str]) -> str:
    data: dict[str, Any] = {
        "project": {
            "name": f"{name}-backend",
            "version": "0.1.0",
            "description": description or f"{name} backend",
            "requires-python": ">=3.12",
            "dependencies": deps,
            "optional-dependencies": {"dev": dev},
        },
        "build-system": {"requires": ["hatchling>=1.25"], "build-backend": "hatchling.build"},
        "tool": {
            "hatch": {"build": {"targets": {"wheel": {"packages": ["app"]}}}},
            "pytest": {"ini_options": {"asyncio_mode": "auto", "testpaths": ["tests"], "addopts": "-q"}},
            "ruff": {"line-length": 120, "target-version": "py312", "lint": {"select": ["E", "F", "I", "B", "UP"], "ignore": ["E501"]}},
            "mypy": {"python_version": "3.12", "ignore_missing_imports": True, "check_untyped_defs": False},
        },
    }
    return tomli_w.dumps(data)


def requirements(deps: list[str]) -> str:
    return "# Pinned by Agent Configurator. Regenerate rather than editing by hand.\n" + "\n".join(deps) + "\n"


def package_json(name: str, mods: list[Module], versions: dict[str, str]) -> str | None:
    deps: dict[str, str] = {}
    dev: dict[str, str] = {}
    for m in mods:
        for pkg in m.node_deps:
            deps[pkg] = versions.get(pkg, m.node_deps[pkg])
        for pkg in m.node_dev_deps:
            dev[pkg] = versions.get(pkg, m.node_dev_deps[pkg])
    if not deps:
        return None
    data = {
        "name": f"{name}-frontend",
        "version": "0.1.0",
        "private": True,
        "type": "module",
        "scripts": {
            "dev": "next dev",
            "build": "next build",
            "start": "next start",
            "lint": "eslint .",
            "typecheck": "tsc --noEmit",
        },
        "dependencies": dict(sorted(deps.items())),
        "devDependencies": dict(sorted(dev.items())),
    }
    return json.dumps(data, indent=2) + "\n"


def _deep_merge(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    out = dict(a)
    for k, v in b.items():
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = _deep_merge(out[k], v)
        elif k in out and isinstance(out[k], list) and isinstance(v, list):
            out[k] = out[k] + [x for x in v if x not in out[k]]
        else:
            out[k] = v
    return out


def compose(fragments: list[dict[str, Any]]) -> str | None:
    merged: dict[str, Any] = {}
    for f in fragments:
        merged = _deep_merge(merged, f)
    if not merged.get("services"):
        return None
    order = ["postgres", "backend", "frontend"]
    services = merged["services"]
    merged["services"] = {k: services[k] for k in sorted(services, key=lambda s: (order.index(s) if s in order else 99, s))}
    out: dict[str, Any] = {"services": merged["services"]}
    if merged.get("volumes"):
        out["volumes"] = dict(sorted(merged["volumes"].items()))
    header = "# Generated by Agent Configurator. Start everything with: docker compose up --build\n"
    return header + yaml.safe_dump(out, sort_keys=False, default_flow_style=False, width=120)


def env_example(groups: list[tuple[str, list[dict[str, Any]]]]) -> str:
    lines = [
        "# Copy to .env and fill in the secrets. Never commit .env.",
        "",
    ]
    seen: set[str] = set()
    for title, envs in groups:
        fresh = [e for e in envs if e["name"] not in seen]
        if not fresh:
            continue
        lines.append(f"# --- {title}")
        for e in fresh:
            seen.add(e["name"])
            if e.get("comment"):
                lines.append(f"# {e['comment']}")
            lines.append(f"{e['name']}={e.get('value', '')}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
